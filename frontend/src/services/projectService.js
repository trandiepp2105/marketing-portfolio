/**
 * Returns all published projects in display order.
 * @returns {Promise<Array<Object>>} Project summaries and case-study content.
 */
export async function getProjects() {
  return projects;
}

/**
 * Returns projects for a brand slug, or an empty array when no projects match.
 * @param {string} brandSlug URL slug of the selected brand.
 * @returns {Promise<Array<Object>>} Matching projects in display order.
 */
export async function getProjectsByBrand(brandSlug) {
  return projects.filter((project) => project.brandSlug === brandSlug);
}

/**
 * Returns one project, or null when the ID is unknown.
 * @param {string} projectId Stable project identifier.
 * @returns {Promise<Object|null>} Matching project.
 */
export async function getProjectById(projectId) {
  return projects.find((project) => project.id === projectId) ?? null;
}
